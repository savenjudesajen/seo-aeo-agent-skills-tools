#!/usr/bin/env python3
"""Repository checks (standard library only). CI runs `python3 tools/check_repo.py`; it exits 1 on any problem.

  python3 tools/check_repo.py            check everything
  python3 tools/check_repo.py --write    regenerate VERSIONS.md, then check

Checks, per skill folder under skills/:
  - SKILL.md starts with a frontmatter block whose `name` equals the folder name (lowercase letters,
    digits and hyphens, at most 64 characters) and whose `description` is 1 to 1,024 characters;
  - `metadata.version` is semver;
  - every skill's row in VERSIONS.md matches its metadata.version, and VERSIONS.md names the plugin version
    in .claude-plugin/plugin.json.
The frontmatter reader handles the subset these files use (plain and quoted scalars, folded `>` blocks,
one nested `metadata:` mapping); anything else is reported, not guessed.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
VERSIONS = ROOT / "VERSIONS.md"
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+$")


def frontmatter(text: str) -> dict:
    if not text.startswith("---\n"):
        raise ValueError("SKILL.md doesn't start with a --- frontmatter block")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError("the frontmatter block isn't closed with ---")
    lines = text[4:end].split("\n")
    out: dict = {}
    nested: dict | None = None
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        indent = len(line) - len(line.lstrip(" "))
        m = re.match(r"^\s*([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not m:
            raise ValueError(f"frontmatter line {i + 1} isn't key: value")
        key, value = m.group(1), m.group(2)
        target = out if indent == 0 else nested
        if target is None:
            raise ValueError(f"frontmatter line {i + 1} is indented outside a mapping")
        if indent == 0:
            nested = None
        if value in (">", ">-", "|", "|-"):
            block = []
            i += 1
            while i < len(lines) and (not lines[i].strip() or len(lines[i]) - len(lines[i].lstrip(" ")) > indent):
                block.append(lines[i].strip())
                i += 1
            joiner = " " if value.startswith(">") else "\n"
            target[key] = joiner.join(b for b in block if b) if value.startswith(">") else "\n".join(block)
            continue
        if value == "" and indent == 0:
            nested = {}
            out[key] = nested
            i += 1
            continue
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        target[key] = value
        i += 1
    return out


def skills() -> list[tuple[str, dict]]:
    found = []
    for d in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        found.append((d.name, frontmatter((d / "SKILL.md").read_text(encoding="utf-8"))))
    return found


def versions_md(rows: list[tuple[str, dict]], plugin_version: str) -> str:
    lines = ["# Versions", "", "Generated by `python3 tools/check_repo.py --write`. Don't edit by hand.", "",
             f"Plugin `seo-aeo-skills`: {plugin_version}", "", "| Skill | Version |", "| -- | -- |"]
    lines += [f"| `{name}` | {fm['metadata']['version']} |" for name, fm in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    problems: list[str] = []
    try:
        rows = skills()
    except (OSError, ValueError) as e:
        print(f"FAIL: {e}")
        return 1
    for name, fm in rows:
        if fm.get("name") != name:
            problems.append(f"{name}: frontmatter name {fm.get('name')!r} isn't the folder name")
        if not NAME_RE.match(name) or len(name) > 64:
            problems.append(f"{name}: the name must be lowercase letters, digits and hyphens, at most 64 characters")
        desc = fm.get("description", "")
        if not 1 <= len(desc) <= 1024:
            problems.append(f"{name}: description is {len(desc)} characters (1 to 1,024)")
        version = (fm.get("metadata") or {}).get("version", "")
        if not SEMVER_RE.match(version):
            problems.append(f"{name}: metadata.version {version!r} isn't semver")
    plugin_version = json.loads((ROOT / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]
    expected = versions_md(rows, plugin_version)
    if "--write" in argv and not problems:
        VERSIONS.write_text(expected, encoding="utf-8")
    current = VERSIONS.read_text(encoding="utf-8") if VERSIONS.exists() else ""
    if current != expected:
        problems.append("VERSIONS.md is out of date: run python3 tools/check_repo.py --write and commit it")
    for p in problems:
        print(f"FAIL: {p}")
    print(f"{len(rows)} skill(s), plugin {plugin_version}: {'OK' if not problems else f'{len(problems)} problem(s)'}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
